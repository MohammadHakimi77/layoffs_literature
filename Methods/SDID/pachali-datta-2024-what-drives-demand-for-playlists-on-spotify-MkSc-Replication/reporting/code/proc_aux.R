# Auxilary functions

# function to generate nice-looking names in table
repl_names <- function(x) sapply(x, function(i) {
  if (grepl('duration', i)) return('Play duration (in h)')
  if (grepl('sigma', i)) return('sigma')
  if (grepl('[_]x[_]playlistage', i)) return('content popularity x playlist novelty')
  if (grepl('[_]x[_]playlist[_]rank', i)) return('content popularity x playlist rank $\\leq$ 100')
  if (grepl('contentqua', i)) return('content popularity')
  if (grepl('any_promo', i)) return('Featured on Search Page')
  if (grepl('has_superstar', i)) return('Addition of Major Label Superstars')
  if (grepl('promo_', i)) return('featured (\\# categories on search page)')
  if (grepl('^followers$', i)) return('Followers')
  if (grepl('toplists', i)) return('promotions (top lists)')
  if (grepl('nsections', i)) return('promotions (\\#categories)')
  if (grepl('trackage[_]year', i)) return('Track age (in years)')
  if (grepl('^universalshare$', i)) return('Content share (Universal)')
  if (grepl('^warnershare$', i)) return('Content share (Warner)')
  if (grepl('^sonyshare$', i)) return('Content share (Sony)')
  if (grepl('trend', i)) return('trend')
  if (grepl('^rec', i)) return('Recommendation intensity')
  if (grepl('^covid', i)) return('covid outbreak')
  if (grepl('^category', i)) return('category fans')
  if (grepl('ac_danceability', i)) return('Danceability')
  if (grepl('ac_energy', i)) return('Energy')
  if (grepl('ac_speechiness', i)) return('Speechiness')
  if (grepl('ac_acousticness', i)) return('Acousticness')
  if (grepl('ac_instrumentalness', i)) return('Instrumentalness')
  if (grepl('ac_liveness', i)) return('Liveness')
  if (grepl('ac_valence', i)) return('Valence')
  if (grepl('ac_tempo', i)) return('Tempo')
  if (grepl('ac_loudness', i)) return('Loudness')
  if (grepl('ml_curr', i)) return('Share of major label tracks (in \\%)')
  if (grepl('update', i)) return('Share of tracks updated')
  
  return(i)
})
